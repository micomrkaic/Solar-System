#!/bin/sh
# Generate horizons_j2000.h: barycentric (SSB) state vectors of the Sun and
# the eight planetary-system barycentres at J2000.0 from JPL Horizons, in the
# ecliptic/J2000 frame, AU and AU/day.  When this header is present the
# Makefile defines HAVE_HORIZONS_J2000 and sim_init() starts from these exact
# osculating states instead of the approximate mean elements table, which
# makes `make test`'s Horizons position check strict (0.1 % of a).
#
#   tests/fetch_j2000_state.sh          # writes ./horizons_j2000.h — commit it
#
# IDs 1–8 are the planetary-system barycentres (3 = Earth–Moon barycentre),
# matching the system masses used in the simulation; 10 is the Sun.
set -eu
JD=2451545.0
OUT="$(dirname "$0")/../horizons_j2000.h"
API="https://ssd.jpl.nasa.gov/api/horizons.api"
{
  echo "/* Generated by tests/fetch_j2000_state.sh on $(date -u +%Y-%m-%d) — do not edit."
  echo "   JPL Horizons state vectors at JD $JD TDB (J2000.0), solar-system"
  echo "   barycentre, ecliptic & mean equinox of J2000, units AU and AU/day."
  echo "   Rows: Sun, Mercury, Venus, Earth–Moon bary., Mars, Jupiter, Saturn,"
  echo "   Uranus, Neptune (system barycentres).                                 */"
  echo "#define HORIZONS_J2000_JD $JD"
  echo "static const double HORIZONS_J2000[9][6] = {"
  for id in 10 1 2 3 4 5 6 7 8; do
    line=$(curl -sS "$API?format=text&COMMAND='$id'&EPHEM_TYPE='VECTORS'&CENTER='500@0'&TLIST='$JD'&REF_PLANE='ECLIPTIC'&VEC_TABLE='2'&OUT_UNITS='AU-D'&CSV_FORMAT='YES'" \
           | awk '/\$\$SOE/{f=1;next} /\$\$EOE/{f=0} f' | head -1)
    [ -n "$line" ] || { echo "no data for body $id" >&2; exit 1; }
    # CSV: JDTDB, Calendar Date (TDB), X, Y, Z, VX, VY, VZ,
    echo "$line" | awk -F',' -v id="$id" '{ for(i=3;i<=8;i++) gsub(/ /,"",$i);
         printf "  { %s, %s, %s,  %s, %s, %s },   /* %s */\n", $3,$4,$5,$6,$7,$8, id }'
  done
  echo "};"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT"; cat "$OUT"
